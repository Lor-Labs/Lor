export type PixelArt = { palette: readonly string[]; rows: readonly string[] }

// One run of same-coloured pixels per row and colour, for SVG paths and
// PNG encoding alike.
export function pixelRuns(art: PixelArt) {
  const byColor = new Map<string, string[]>()
  art.rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const key = row[x] ?? "."
      if (key === ".") {
        x++
        continue
      }
      let end = x + 1
      while (end < row.length && row[end] === key) end++
      const color = art.palette[PIXEL_KEYS.indexOf(key)]
      if (color) {
        const runs = byColor.get(color) ?? []
        runs.push(`M${x} ${y}h${end - x}v1h${x - end}z`)
        byColor.set(color, runs)
      }
      x = end
    }
  })
  return [...byColor].map(([color, runs]) => ({ color, d: runs.join("") }))
}

export function pixelColor(art: PixelArt, x: number, y: number) {
  const key = art.rows[y]?.[x] ?? "."
  return key === "." ? null : (art.palette[PIXEL_KEYS.indexOf(key)] ?? null)
}

const BY_ID = new Map(CREATURES.map((creature) => [creature.id, creature]))

export function isCreatureId(value: unknown): value is CreatureId {
  return typeof value === "string" && BY_ID.has(value as CreatureId)
}

export function creatureById(id: CreatureId): Creature {
  return BY_ID.get(id) ?? (CREATURES[0] as Creature)
}

function hash(text: string, seed: number) {
  let h = seed >>> 0
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 16777619) >>> 0
  }
  return h
}

export const AGENT_NAME_MAX = 24

// A name people typed for the agent, cleaned; null when nothing usable is
// left. Mentions are by id, so a name only needs to read well.
export function normalizeAgentName(value: string): string | null {
  const name = value
    .replace(/[<>@#`*_~|]/g, "")
    .replace(/\s+/g, " ")
    .trim()
  return name ? name.slice(0, AGENT_NAME_MAX).trim() : null
}

// A channel's agent: the name and creature the team picked, else ones
// derived from the channel id so they stay put until someone changes them.
export function channelAgentIdentity(channel: {
  id: string
  agentName?: string | null
  agentCreature?: string | null
}): { name: string; creature: CreatureId } {
  const creature = isCreatureId(channel.agentCreature)
    ? channel.agentCreature
    : (CREATURES[hash(channel.id, 2166136261) % CREATURES.length] as Creature)
        .id
  const names = creatureById(creature).names
  const name =
    channel.agentName?.trim() ||
    names[hash(channel.id, 374761393) % names.length] ||
    "Lor"
  return { name, creature }
}
