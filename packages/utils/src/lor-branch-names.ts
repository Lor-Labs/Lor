// The place name a session's branch gets. Picked from the session id alone,
// so the same session always names the same branch and the server and the
// clients that show a branch before the server confirms (web, mobile) agree.
export function lorBranchPlaceName(sessionId: string): string {
  return LOR_BRANCH_NAMES[branchNameIndex(sessionId)] ?? "session"
}

// FNV-1a over the id, kept small: ids are uuids, so any spread works and this
// needs no dependency and stays identical in every runtime.
function branchNameIndex(sessionId: string): number {
  let hash = 0x811c9dc5
  for (let i = 0; i < sessionId.length; i += 1) {
    hash ^= sessionId.charCodeAt(i)
    hash = Math.imul(hash, 0x01000193)
  }
  return (hash >>> 0) % LOR_BRANCH_NAMES.length
}
