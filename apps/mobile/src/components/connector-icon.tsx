export type ConnectorKey = "github" | "linear" | "datadog"

const CONNECTORS: Record<
  ConnectorKey,
  { host: RegExp; tools: readonly string[] }
> = {
  github: {
    host: /(^|\.)github\.com$/i,
    tools: ["search_github", "fetch_github"],
  },
  linear: {
    host: /(^|\.)linear\.app$/i,
    tools: [
      "search_linear",
      "fetch_linear",
      "create_linear_issue",
      "comment_linear",
    ],
  },
  datadog: {
    host: /(^|\.)datadoghq\.(com|eu)$/i,
    tools: ["search_datadog_logs", "analyze_datadog_logs"],
  },
}

const connectorKeys = Object.keys(CONNECTORS) as ConnectorKey[]

export function connectorForTool(toolName: string): ConnectorKey | null {
  return (
    connectorKeys.find((key) => CONNECTORS[key].tools.includes(toolName)) ??
    null
  )
}

export function connectorForName(name?: string | null): ConnectorKey | null {
  if (!name) return null
  const normalized = name.toLowerCase()
  return connectorKeys.find((key) => key === normalized) ?? null
}

export function connectorForUrl(url?: string): ConnectorKey | null {
  if (!url) return null
  try {
    const host = new URL(url).hostname
    return connectorKeys.find((key) => CONNECTORS[key].host.test(host)) ?? null
  } catch {
    return null
  }
}

